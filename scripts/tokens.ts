/**
 * pnpm tokens: extracts the design tokens from "Zamane Design System.html" (read-only) into
 * src/client/styles/tokens.css. pnpm tokens:check fails when that file has drifted from the design system, and
 * reports any token whose value in the designs' shared layer (.ux-forge/goals/zamane.css) differs from it.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const DS = join(ROOT, "Zamane Design System.html");
const OUT = join(ROOT, "src/client/styles/tokens.css");
const DESIGN_LAYER = join(ROOT, ".ux-forge/goals/zamane.css");

function extract(source: string): string {
  const lines = source.split(/\r?\n/);
  const pick = (re: RegExp, what: string) => {
    const line = lines.find((l) => re.test(l));
    if (!line) throw new Error(`tokens: couldn't find ${what} in the design system`);
    return line.trim();
  };
  const light = pick(/^:root\{--surface:/, "the light colour tokens");
  const darkMedia = pick(
    /^@media \(prefers-color-scheme: dark\)\{:root:not\(\[data-theme="light"\]\)\{--surface:/,
    "the system dark tokens",
  );
  const darkForced = pick(/^:root\[data-theme="dark"\]\{--surface:/, "the forced dark tokens");
  const scale = pick(/^:root \{ --font-serif:/, "the type, space and radius tokens");
  return [
    '/* Generated by `pnpm tokens` from "Zamane Design System.html". Do not edit; run `pnpm tokens:check` in CI. */',
    light,
    darkMedia,
    darkForced,
    scale,
    "",
  ].join("\n");
}

function declarations(css: string): Map<string, string> {
  // Keyed by the block they appear in (light, system-dark, forced-dark) so the dark values compare separately.
  const out = new Map<string, string>();
  const blocks = [
    ["light", /(?:^|\n):root\s*\{([^}]*)\}/g],
    ["dark", /:root\[data-theme="dark"\]\s*\{([^}]*)\}/g],
  ] as const;
  for (const [name, re] of blocks) {
    for (const m of css.matchAll(re)) {
      for (const d of m[1]!.split(";")) {
        const i = d.indexOf(":");
        if (i < 0) continue;
        const k = d.slice(0, i).trim();
        if (k.startsWith("--"))
          out.set(
            `${name} ${k}`,
            d
              .slice(i + 1)
              .trim()
              .replace(/\s+/g, " ")
              .replace(/\s*,\s*/g, ","),
          );
      }
    }
  }
  return out;
}

const generated = extract(readFileSync(DS, "utf8"));
if (process.argv.includes("--check")) {
  let failed = false;
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== generated) {
    console.error("tokens.css has drifted from the design system. Run `pnpm tokens`.");
    failed = true;
  }
  if (existsSync(DESIGN_LAYER)) {
    const ds = declarations(generated);
    const layer = declarations(readFileSync(DESIGN_LAYER, "utf8"));
    const diffs = [...layer].filter(([k, v]) => ds.has(k) && ds.get(k) !== v);
    for (const [k, v] of diffs) console.warn(`design layer differs: ${k} is "${v}", design system says "${ds.get(k)}"`);
    if (!diffs.length) console.log("design layer tokens match the design system");
  }
  if (failed) process.exit(1);
  console.log("tokens.css matches the design system");
} else {
  writeFileSync(OUT, generated);
  console.log(`wrote ${OUT}`);
}
